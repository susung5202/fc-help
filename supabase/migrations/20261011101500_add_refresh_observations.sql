create table if not exists public.refresh_observations (
  id bigint generated by default as identity primary key,
  player_spid bigint,
  player_name text not null,
  season_name text not null,
  observation_kind text not null check (observation_kind in ('exact','range')),
  start_hour_type text not null check (start_hour_type in ('odd','even','every')),
  start_minute integer not null check (start_minute between 0 and 59),
  end_hour_type text not null check (end_hour_type in ('odd','even','every')),
  end_minute integer not null check (end_minute between 0 and 59),
  source_type text not null check (source_type in ('scraped_public','user_report','manual','fc_help')),
  source_name text not null,
  source_url text not null,
  source_observation_count integer not null default 1 check (source_observation_count > 0),
  source_status text not null default 'estimated' check (source_status in ('estimated','reported','confirmed')),
  source_observed_date date,
  observer_key text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    observation_kind <> 'exact'
    or (
      start_hour_type = end_hour_type
      and start_minute = end_minute
    )
  )
);

create unique index if not exists refresh_observations_source_pattern_uidx
on public.refresh_observations (
  source_url,
  player_name,
  season_name,
  observation_kind,
  start_hour_type,
  start_minute,
  end_hour_type,
  end_minute
);

create index if not exists refresh_observations_player_spid_idx
on public.refresh_observations (player_spid);

create index if not exists refresh_observations_name_season_idx
on public.refresh_observations (player_name, season_name);

