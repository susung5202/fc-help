  start_minute,
  end_hour_type,
  end_minute,
  source_type,
  source_name,
  source_url,
  source_observation_count,
  source_status,
  source_observed_date,
  observer_key
)
select
  r.player_spid,
  coalesce(r.player_name, '선수명 미확인'),
  coalesce(r.season_name, '시즌 미확인'),
  'exact',
  r.hour_type,
  r.refresh_minute,
  r.hour_type,
  r.refresh_minute,
  'user_report',
  'FC Help 유저 제보',
  'https://fchelp.xyz/refresh/' || r.player_spid::text || '#report-' || r.id::text,
  1,
  'reported',
  (r.created_at at time zone 'Asia/Seoul')::date,
  case
    when r.user_id is not null then 'user:' || r.user_id::text
    else 'report:' || r.id::text
  end
from public.refresh_reports r
where r.hour_type <> 'unknown'
  and r.refresh_minute is not null
on conflict do nothing;
