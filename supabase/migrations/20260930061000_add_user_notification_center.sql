create table if not exists public.user_notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  actor_id uuid references auth.users(id) on delete set null,
  type text not null check (type in (
    'community_comment',
    'community_reply',
    'community_like',
    'squad_comment',
    'squad_reply',
    'squad_like',
    'squad_comment_like',
    'report_resolved',
    'report_dismissed'
  )),
  title text not null,
  body text not null default '',
  href text not null,
  source_key text not null unique,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists user_notifications_user_created_idx
  on public.user_notifications (user_id, created_at desc);
create index if not exists user_notifications_user_unread_idx
  on public.user_notifications (user_id, read_at, created_at desc);

alter table public.user_notifications enable row level security;

revoke all on table public.user_notifications from anon, authenticated;
grant select on table public.user_notifications to authenticated;
grant update (read_at) on table public.user_notifications to authenticated;

drop policy if exists "user_notifications_select_own" on public.user_notifications;
create policy "user_notifications_select_own"
on public.user_notifications for select
to authenticated
using ((select auth.uid()) = user_id);

drop policy if exists "user_notifications_update_own" on public.user_notifications;
create policy "user_notifications_update_own"
on public.user_notifications for update
to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

create schema if not exists private;

create or replace function private.notify_community_comment()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  recipient uuid;
  actor_name text;
  preview text;
  kind text;
begin
  select coalesce(nullif(p.display_name, ''), '구단주')
    into actor_name
  from public.profiles p
  where p.id = new.user_id;
  actor_name := coalesce(actor_name, '구단주');
  preview := left(regexp_replace(new.content, '[\n\r]+', ' ', 'g'), 100);

  if new.parent_id is not null then
    select c.user_id into recipient
    from public.community_comments c
    where c.id = new.parent_id;
    kind := 'community_reply';
  else
    select p.author_id into recipient
    from public.community_posts p
    where p.id = new.post_id;
    kind := 'community_comment';
  end if;

  if recipient is null or recipient = new.user_id then
    return new;
  end if;

  insert into public.user_notifications (user_id, actor_id, type, title, body, href, source_key)
  values (
    recipient,
    new.user_id,
    kind,
    case when kind = 'community_reply' then '내 댓글에 답글이 달렸어요' else '내 게시글에 댓글이 달렸어요' end,
    actor_name || ' · ' || preview,
    '/community/' || new.post_id::text,
    'community_comment:' || new.id::text
  )
  on conflict (source_key) do nothing;

  return new;
end;
$$;
revoke all on function private.notify_community_comment() from public, anon, authenticated;

drop trigger if exists trg_notify_community_comment on public.community_comments;
create trigger trg_notify_community_comment
after insert on public.community_comments
for each row execute function private.notify_community_comment();

