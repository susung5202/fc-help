create or replace function private.notify_report_status()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  kind text;
  default_body text;
begin
  if new.status is not distinct from old.status then
    return new;
  end if;
  if new.status not in ('resolved', 'dismissed') then
    return new;
  end if;

  if new.status = 'resolved' then
    kind := 'report_resolved';
    default_body := '신고한 내용을 관리자가 처리했습니다.';
  else
    kind := 'report_dismissed';
    default_body := '신고 내용을 검토한 결과 기각되었습니다.';
  end if;

  insert into public.user_notifications (user_id, actor_id, type, title, body, href, source_key)
  values (
    new.reporter_id,
    new.resolved_by,
    kind,
    case when new.status = 'resolved' then '신고가 처리되었습니다' else '신고가 기각되었습니다' end,
    coalesce(nullif(trim(new.resolution_note), ''), default_body),
    '/mypage/reports',
    'report:' || new.id::text || ':' || new.status
  )
  on conflict (source_key) do nothing;

  return new;
end;
$$;
revoke all on function private.notify_report_status() from public, anon, authenticated;

drop trigger if exists trg_notify_report_status on public.content_reports;
create trigger trg_notify_report_status
after update of status on public.content_reports
for each row execute function private.notify_report_status();